"""
Dataset assembly: normalisation, voltages, merging, and train/test/val export.

Both pipelines in this package produce per-host energies. This module turns those into
the CSV files used to train generative models, and is the single place where the voltage
convention is defined, so that datasets generated by different pipelines remain comparable.

Voltage convention: V_X = -(E_{X_nHost} - E_Host - n * mu_X) / (n * z * e) + E0(X+/X),
expressed vs. SHE. The SHE shift is folded into the bulk reference energies passed in
(see SHE_REFERENCED_BULK_ENERGIES).
"""
import logging
import os

import pandas as pd
from pymatgen.core import Structure

logger = logging.getLogger(__name__)

# Standard electrode potentials E0(X+/X) in V, which put each ion's voltage on the
# common SHE scale. The pipelines store insertion energies referenced to the *unshifted*
# bulk energies, so this shift is applied exactly once, here.
SHE_POTENTIALS = {"Li": -3.04, "Na": -2.71}

# Ion charge (z) for the voltage denominator.
ION_VALENCE = {"Li": 1, "Na": 1, "K": 1, "Mg": 2, "Ca": 2, "Zn": 2}

# Columns the training CSVs are expected to carry, in order.
CSV_COLUMNS = ["pretty_formula", "material_id", "num_atoms", "host_energy_per_atom",
               "Li_energy_per_atom", "Na_energy_per_atom", "Li_voltage", "Na_voltage",
               "host_structure", "cif", "Na_structure"]


def _as_structure(value):
    """Accepts a Structure, a JSON/CIF string, or None; returns a Structure or None."""
    if value is None or isinstance(value, float):
        return None
    if isinstance(value, Structure):
        return value
    if isinstance(value, str):
        if not value.strip():
            return None
        return Structure.from_str(value, fmt="json" if value.lstrip().startswith("{") else "cif")
    return None


def normalize_dataset(df: pd.DataFrame, source: str, working_ion: str = "Li",
                      new_working_ion: str = "Na") -> pd.DataFrame:
    """
    Maps a pipeline's output onto the canonical column schema.

    Handles both the insertion-electrode pipeline (which names the host after the MP
    charge material) and the interstitial pipeline (which constructs its own host), and
    tags each row with `source` so the two remain distinguishable after merging.

    Args:
        df (pd.DataFrame): Raw output from either pipeline.
        source (str): Identifier recorded in the 'source' column (e.g. "mp_electrodes").
        working_ion (str): Primary ion (e.g. "Li").
        new_working_ion (str): Substituted ion (e.g. "Na").

    Returns:
        pd.DataFrame: Canonical columns: host_mp_id, source, host_structure,
                      host_energy_per_atom, {ion}_structure, {ion}_energy_per_atom,
                      pretty_formula, num_atoms, and N where available.
    """
    out = pd.DataFrame(index=df.index)

    id_column = next((c for c in ("host_mp_id", "material_id", "mp_id", "charge_id")
                      if c in df.columns), None)
    if id_column is None:
        raise KeyError("No material identifier column found (host_mp_id/material_id/mp_id/charge_id).")
    out["host_mp_id"] = df[id_column]
    out["source"] = source

    for column in ("host_structure", "host_energy_per_atom",
                   f"{working_ion}_structure", f"{working_ion}_energy_per_atom",
                   f"{new_working_ion}_structure", f"{new_working_ion}_energy_per_atom",
                   f"{working_ion}_dE", f"{new_working_ion}_dE", "N", "status"):
        if column in df.columns:
            out[column] = df[column]

    ion_structures = out.get(f"{working_ion}_structure")
    if ion_structures is not None:
        structures = ion_structures.apply(_as_structure)
        out["num_atoms"] = structures.apply(lambda s: len(s) if s is not None else 0)
        out["pretty_formula"] = structures.apply(
            lambda s: s.composition.reduced_formula if s is not None else None)

        # The insertion-electrode pipeline does not record N; recover it as the difference
        # in working-ion count between the inserted structure and the host.
        if "N" not in out.columns and "host_structure" in out.columns:
            hosts = out["host_structure"].apply(_as_structure)
            out["N"] = [
                _ion_count(full, working_ion) - _ion_count(host, working_ion)
                if full is not None and host is not None else -1
                for full, host in zip(structures, hosts)
            ]

    return out


def _ion_count(structure, ion: str) -> int:
    """Number of `ion` atoms in a structure."""
    return int(structure.composition.get_el_amt_dict().get(ion, 0))


def compute_voltages(df: pd.DataFrame, working_ions=("Li", "Na"),
                     she_potentials: dict | None = None) -> pd.DataFrame:
    """
    Adds `{ion}_voltage` columns (V vs. SHE) derived from stored insertion energies.

    Applies V = -dE / (N * z) + E0(X+/X), where dE is the insertion energy stored by the
    pipeline (referenced to the unshifted bulk energy), N the number of inserted ions, z
    the ion charge, and E0 the standard electrode potential. Rows with N <= 0 or a missing
    dE get NaN.

    Args:
        df (pd.DataFrame): Normalised dataset carrying `{ion}_dE` and `N`.
        working_ions (tuple): Ions to compute voltages for.
        she_potentials (dict | None): Standard electrode potentials. Defaults to SHE_POTENTIALS.

    Returns:
        pd.DataFrame: A copy of `df` with voltage columns added.
    """
    she_potentials = she_potentials or SHE_POTENTIALS
    out = df.copy()

    if "N" not in out.columns:
        raise KeyError("compute_voltages requires an 'N' column (number of inserted ions).")

    n_ions = pd.to_numeric(out["N"], errors="coerce")
    n_ions = n_ions.where(n_ions > 0)

    for ion in working_ions:
        dE_column = f"{ion}_dE"
        if dE_column not in out.columns:
            logger.warning(f"Skipping {ion} voltage: '{dE_column}' is missing.")
            continue

        dE = pd.to_numeric(out[dE_column], errors="coerce")
        valence = ION_VALENCE.get(ion, 1)
        out[f"{ion}_voltage"] = -dE / (n_ions * valence) + she_potentials[ion]

    return out


def merge_datasets(dfs: list, structure_matcher=None) -> pd.DataFrame:
    """
    Concatenates normalised datasets and keeps the lowest-energy entry per host and
    stoichiometry, generalising the deduplication rule already used for the
    insertion-electrode dataset.

    Not yet used in production: it becomes relevant once both generations are computed
    with the same MLIP. Deduplication currently keys on (pretty_formula, num_atoms);
    passing a StructureMatcher to compare host structures is the intended refinement.

    Args:
        dfs (list): Normalised DataFrames.
        structure_matcher: Reserved for structure-based host matching.

    Returns:
        pd.DataFrame: Merged, deduplicated dataset.
    """
    if structure_matcher is not None:
        raise NotImplementedError("Structure-based host matching is not implemented yet.")

    merged = pd.concat(dfs, ignore_index=True)
    before = len(merged)
    energy_column = "Li_energy_per_atom"
    if energy_column in merged.columns:
        keep = merged.groupby(["pretty_formula", "num_atoms"])[energy_column].idxmin()
        merged = merged.loc[keep.dropna()].reset_index(drop=True)
    logger.info(f"Merged {before} rows down to {len(merged)} after deduplication.")
    return merged


def split_and_export(df: pd.DataFrame, out_dirpath: str, max_atoms: int | None = 20,
                     seed: int = 42, fractions=(0.8, 0.1, 0.1)) -> dict:
    """
    Writes train/test/val CSVs in the format consumed by the generative model.

    This is the single definition of the training split; both the insertion-electrode and
    interstitial datasets go through it.

    Args:
        df (pd.DataFrame): Dataset carrying voltages and structures.
        out_dirpath (str): Directory for train.csv / test.csv / val.csv.
        max_atoms (int | None): Keep structures with at most this many atoms (inclusive,
            matching the "<= 20 atoms/cell" convention of the published dataset). Note the
            standalone create_csv.py script used a strict "< 20"; pass max_atoms=19 to
            reproduce that exactly.
        seed (int): Shuffle seed.
        fractions (tuple): (train, test, val) fractions; must sum to 1.

    Returns:
        dict: Split name -> row count.
    """
    os.makedirs(out_dirpath, exist_ok=True)
    out = df.copy()

    if max_atoms is not None:
        out = out[out["num_atoms"] <= max_atoms]
    out = out.dropna(subset=["host_energy_per_atom", "Li_energy_per_atom"]).reset_index(drop=True)

    out = out.rename(columns={"host_mp_id": "material_id", "Li_structure": "cif"})
    for column in ("host_structure", "cif", "Na_structure"):
        if column in out.columns:
            out[column] = out[column].apply(
                lambda value: (_as_structure(value).to(fmt="cif")
                               if _as_structure(value) is not None else ""))

    columns = [c for c in CSV_COLUMNS if c in out.columns]
    out = out[columns]

    shuffled = out.sample(frac=1, random_state=seed).reset_index(drop=True)
    n = len(shuffled)
    train_end = int(fractions[0] * n)
    test_end = int((fractions[0] + fractions[1]) * n)

    splits = {"train": shuffled.iloc[:train_end],
              "test": shuffled.iloc[train_end:test_end],
              "val": shuffled.iloc[test_end:]}

    counts = {}
    for name, split in splits.items():
        split.to_csv(os.path.join(out_dirpath, f"{name}.csv"), index=False)
        counts[name] = len(split)
        logger.info(f"{name}: {len(split)} rows ({len(split) / n * 100:.1f}%)" if n else f"{name}: 0 rows")

    return counts
